import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const source = process.argv[2] ?? fileURLToPath(new URL('../supabase/migrations/',import.meta.url));
const target = process.argv[3] ?? resolve(source,'../elden-bootstrap.sql');
const newest = process.argv[4] ?? resolve(source,'202609290004_homepage.sql');
const names=['202609290001_initial_schema.sql','202609290002_business_foundation.sql','202609290003_access_and_onboarding.sql','202609290004_homepage.sql'];
let sql=`-- ELDEN MEDIA | NEW PROJECT ONLY | schema 202609290004\n-- One-time bootstrap. Existing projects must apply only missing migrations.\n-- Generated from four migrations; do not edit this file independently.\n-- Google login, QR workflow, Excel parser and UI still need implementation.\nbegin;\ndo $$ begin\n if to_regclass('public.profiles') is not null then\n  raise exception 'Existing Elden schema detected. Do not run bootstrap; apply only missing migrations.';\n end if;\nend; $$;\n`;
for(const name of names){
  const raw=readFileSync(name===names[3]?newest:resolve(source,name),'utf8');
  const inner=raw.replace(/^begin;\s*$/mi,'').replace(/^commit;\s*$/mi,'');
  sql+=`\n-- ===== ${name} =====\n${inner}\n`;
}
sql+='\ncommit;\n';
writeFileSync(target,sql,'utf8');
console.log('Bootstrap generated:',target);
