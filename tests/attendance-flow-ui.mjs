import assert from 'node:assert/strict';
import { entryState, groupIdolOperations, nextIdolTurn, lateMinutes } from '../src/lib/operations-flow.ts';
const at = time => Date.parse(`2026-10-01T${time}+07:00`);
const first = { segment_id:'a',idol_id:'idol-a',idol_name:'Lan',username:'lan',work_date:'2026-10-01',room_id:'room-a',room_code:'P101',scheduled_start:'2026-10-01T09:00:00+07:00',entry_due_at:'2026-10-01T09:00:00+07:00',status:'waiting',room_on_hold:false,late_seconds:0 };
assert.equal(entryState(first,at('08:29:59')),'early');
assert.equal(entryState(first,at('08:30:00')),'ready');
assert.equal(entryState(first,at('09:00:00')),'ready');
assert.equal(entryState(first,at('09:00:01')),'overdue');
assert.equal(entryState({...first,entry_due_at:null},at('15:00:00')),'blocked');
assert.equal(entryState({...first,room_on_hold:true},at('15:00:00')),'blocked');
assert.equal(entryState({...first,status:'completed'},at('15:00:00')),'completed');
const later = {...first,segment_id:'b',room_id:'borrowed-room',room_code:'P201',scheduled_start:'2026-10-01T12:00:00+07:00',late_seconds:61};
assert.equal(nextIdolTurn([later,first]).segment_id,'a');
assert.equal(nextIdolTurn([first,{...later,status:'in_room'}]).segment_id,'b');
assert.equal(nextIdolTurn([{...first,status:'skipped'}]),undefined);
assert.deepEqual([-1,0,1,59,60,61].map(lateMinutes),[0,0,1,1,1,2]);
const groups=groupIdolOperations([later,first,{...first,idol_id:'idol-b'},{...first,work_date:'2026-10-02'}]);
assert.equal(groups.length,3);
assert.equal(groups[0].rows.length,2);
assert.equal(groups[0].rows[1].room_code,'P201');
assert.equal(groups[0].late_minutes,2);
console.log('15 attendance UI rule checks passed.');
